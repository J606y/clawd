import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { buildTurns, withoutInFlight } = await server.ssrLoadModule('/src/lib/transcript.ts');
  const FOOTER = '[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]';
  const wake = {
    role: 'user',
    display_kind: 'internal_notification',
    timestamp: 100,
    content: `[ASYNC DELEGATION BATCH COMPLETE — deleg_33e2c029]\nA background fan-out unit...\nRole: leaf   Model: ?   Total duration: 246.73s\n\n**结论**：报告正文\n\n${FOOTER}`,
  };
  const human = (content, timestamp) => ({ role: 'user', content, timestamp });
  const reply = (content, timestamp) => ({ role: 'assistant', content, timestamp });
  const calling = (timestamp) => ({ role: 'assistant', content: '', timestamp, tool_calls: [{ id: `c${timestamp}`, function: { name: 'terminal', arguments: '{}' } }] });

  test('wake notification becomes a notice, not a user bubble, and opens its own assistant turn', () => {
    const turns = buildTurns([human('查一下', 1), reply('好的', 2), wake, reply('已处理', 130)]);
    assert.deepEqual(turns.map((t) => t.role), ['user', 'assistant', 'notice', 'assistant']);
    const n = turns[2];
    assert.equal(n.title, '后台子任务完成');
    assert.equal(n.failed, false);
    assert.equal(n.seconds, 246.73);
    assert.ok(n.detail.endsWith('**结论**：报告正文'), 'footer stripped');
    assert.equal(turns[3].startedAt, 100);
    assert.equal(turns[3].text, '已处理');
  });

  test('delivery row uses display metadata (object or JSON string) for failure and duration', () => {
    const asObject = { role: 'user', display_kind: 'async_delegation_complete', content: 'x', display_metadata: { failed_count: 1, duration_seconds: 12 } };
    const asString = { ...asObject, display_metadata: JSON.stringify({ failed_count: 0, duration_seconds: 3 }) };
    const [a, b] = buildTurns([asObject, asString]);
    assert.deepEqual([a.title, a.failed, a.seconds], ['后台子任务失败', true, 12]);
    assert.deepEqual([b.title, b.failed, b.seconds], ['后台子任务完成', false, 3]);
  });

  test('failed task header, process completion and unknown kinds get their own titles', () => {
    const turns = buildTurns([
      { role: 'user', display_kind: 'internal_notification', content: '[ASYNC DELEGATION TASK FAILED — deleg_x, task 2/3]\nboom' },
      { role: 'user', display_kind: 'process_complete', content: '[IMPORTANT: background process finished]', display_metadata: { display_text: 'Background Process Finished: ls' } },
      { role: 'user', display_kind: 'internal_notification', content: 'Cronjob Response: ok' },
    ]);
    assert.deepEqual(turns.map((t) => [t.title, t.failed, t.seconds]), [
      ['后台子任务失败', true, undefined],
      ['后台命令已结束', false, undefined],
      ['系统通知', false, undefined],
    ]);
  });

  test('hidden and suppressed rows render nothing but still split assistant turns', () => {
    const turns = buildTurns([
      human('a', 1),
      reply('one', 2),
      { role: 'user', display_kind: 'hidden', content: '' },
      reply('two', 3),
      { role: 'user', display_kind: 'async_delegation_complete', content: 'x', display_metadata: { presentation_suppressed: true } },
    ]);
    assert.deepEqual(turns.map((t) => t.role), ['user', 'assistant', 'assistant']);
    assert.deepEqual(turns.slice(1).map((t) => t.text), ['one', 'two']);
  });

  test('withoutInFlight ignores trailing notices after a completed reply', () => {
    const msgs = [human('a', 1), reply('done', 2), wake];
    assert.equal(withoutInFlight(msgs), msgs);
  });

  test('withoutInFlight cuts from the last human message, never from a notice', () => {
    const msgs = [human('a', 1), reply('done', 2), human('b', 3), calling(4), wake, calling(5)];
    assert.deepEqual(withoutInFlight(msgs), msgs.slice(0, 2));
  });
} finally {
  await server.close();
}
