import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
const { buildTurns, isTurnStart, withoutInFlight, visibleTurnsBesideLive } = await server.ssrLoadModule('/src/lib/transcript.ts');
const owner = 'f95f9922-c23e-560a-ada5-c1ac6dfdf108';
const input = (extra = {}) => ({ id: 3, role: 'user', content: 'synthetic user input', timestamp: 200, display_kind: 'internal_notification', input_origin: 'api_queue', display_metadata: { gateway_input_owner: owner }, ...extra });
const prior = [{ id: 1, role: 'user', content: 'previous input', timestamp: 100 }, { id: 2, role: 'assistant', content: 'previous answer', timestamp: 101 }];
const calling = { id: 4, role: 'assistant', content: '', reasoning: 'saved thought', timestamp: 201, tool_calls: [{ id: 'call1', function: { name: 'terminal', arguments: '{}' } }] };
try {
  await test('admission provenance, not owner shape, determines API input and steering', () => {
    const admitted = input({ display_metadata: {} });
    assert.equal(buildTurns([admitted])[0].role, 'user');
    assert.equal(isTurnStart(admitted), true);
    const unknown = input({ input_origin: undefined });
    assert.equal(buildTurns([unknown])[0].role, 'notice');
    assert.equal(isTurnStart(unknown), false);
    const steer = input({ input_origin: 'api_steer', content: '[OUT-OF-BAND USER MESSAGE]\nnew instruction\n[/OUT-OF-BAND USER MESSAGE]' });
    const turn = buildTurns([steer])[0];
    assert.equal(turn.role, 'user');
    assert.equal(turn.steer, true);
    assert.equal(turn.text, 'new instruction');
    assert.equal(turn.message, undefined);
    assert.equal(isTurnStart(steer), false);
  });
  await test('owned plain legacy input renders once as a non-editable user turn and a task boundary', () => {
    for (const metadata of [{ gateway_input_owner: owner }, JSON.stringify({ gateway_input_owner: owner })]) {
      const row = input({ display_metadata: metadata });
      const turns = buildTurns([row]);
      assert.equal(turns.length, 1);
      assert.equal(turns[0].role, 'user');
      assert.equal(turns[0].text, row.content);
      assert.equal(turns[0].message, undefined, 'legacy provenance must not grant edit permission');
      assert.equal(isTurnStart(row), true);
    }
  });
  await test('ongoing return-to-session preserves the previous completed turn for legacy input', () => {
    const rows = [...prior, input(), calling];
    // React strips the in-flight turn only when the live projection owns the process.
    const turns = visibleTurnsBesideLive(rows, { startedAt: 200000, steps: [{ kind: 'tool', status: 'running' }], text: '', thinking: '' }, { localActive: true, ownsHistory: false });
    assert.deepEqual(turns.map((turn) => turn.role), ['user', 'assistant']);
    assert.equal(turns[1].text, 'previous answer');
  });
  await test('ambiguous notification cannot make clipping cross an earlier completed reply', () => {
    const rows = [...prior, input({ display_metadata: {}, input_origin: undefined }), calling];
    assert.deepEqual(withoutInFlight(rows), rows, 'no proven current boundary: retain history');
    const ambiguous = [input({ display_metadata: {}, input_origin: undefined }), calling];
    assert.deepEqual(withoutInFlight(ambiguous), ambiguous, 'unidentified input must remain visible even without a prior completed reply');
    assert.deepEqual(withoutInFlight([calling]), [], 'a page consisting only of unfinished process remains owned by live rendering');
  });
  await test('real machinery stays notice or suppressed even when owned', () => {
    for (const row of [
      input({ content: '[ASYNC DELEGATION BATCH COMPLETE — deleg_fixture]\nresult' }),
      input({ content: 'Cronjob Response: fixture' }),
      input({ content: '[System: fixture]' }),
      input({ content: '[Your active task list was preserved]' }),
      input({ content: '[面板自动续跑] fixture' }),
      input({ content: 'synthetic notice\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]' }),
      input({ display_metadata: { gateway_input_owner: owner, display_text: 'producer card' } }),
      input({ display_kind: 'process_complete' }),
      input({ display_kind: 'new_machinery_kind' }),
      input({ display_metadata: { gateway_input_owner: owner, reply_expected: false } }),
    ]) {
      assert.equal(buildTurns([row])[0]?.role, 'notice');
      assert.equal(isTurnStart(row), row.content.startsWith('[面板自动续跑]'));
    }
    for (const row of [input({ display_kind: 'hidden' }), input({ display_metadata: { gateway_input_owner: owner, presentation_suppressed: true } })]) {
      assert.deepEqual(buildTurns([row]), []);
    }
  });
  await test('normal clipping, final reload, and observed-history user identity remain stable', () => {
    const rows = [...prior, input(), calling];
    assert.deepEqual(withoutInFlight(rows), prior);
    assert.deepEqual(withoutInFlight(rows, 200), [...prior, rows[2]]);
    const ended = [...rows, { id: 5, role: 'assistant', content: 'done', timestamp: 210 }];
    assert.equal(withoutInFlight(ended), ended);
  });

  // plan-mode light_note() in plan_mode/render.py; Hermes appends pre_llm_call context as content + "\n\n" + injection
  // (public agent/turn_context.py compose_user_api_content). Synthetic plans path only.
  const lightNote = (plansDir, levers = ['bridge', 'blocked', 'skill']) => {
    const base = `Plan mode is ON. Plans directory: ${plansDir}. Submit with plan_mode; do not ask "should I proceed?" in prose.`;
    if (base.length > 400) return base.slice(0, 400);
    const extra = {
      bridge: ' If plan_mode is not in your tool list: tool_call(calls=[{"name": "plan_mode", "arguments": {"action": "submit"}}]).',
      blocked: ' Terminal and execute_code stay blocked until approval.',
      skill: ' Do not load planning, TDD or debugging skills.',
    };
    const sentences = [base];
    for (const lever of ['bridge', 'blocked', 'skill']) if (levers.includes(lever)) sentences.push(extra[lever]);
    while (sentences.join('').length > 400) sentences.pop();
    return sentences.join('');
  };
  const NOTE = lightNote('/tmp/fixture-plans');
  const shown = (turns) => turns.map((turn) => `${turn.role}:${turn.text ?? ''}:${turn.detail ?? ''}`).join('\n');
  for (const modulePath of ['/src/lib/transcript.ts', '/src/react/lib/transcript.ts']) {
    const api = await server.ssrLoadModule(modulePath);
    await test(`appended plan-mode tail is removed and refresh projection stays stable (${modulePath})`, () => {
      const row = { id: 9, role: 'user', content: `合成的用户原文\n\n${NOTE}`, timestamp: 3 };
      const stored = JSON.stringify(row);
      const turns = api.buildTurns([row]);
      assert.equal(JSON.stringify(row), stored, 'display projection must not rewrite the stored message');
      assert.deepEqual(api.buildTurns([row]), turns, 'refresh uses the same projection');
      assert.equal(turns.filter((turn) => turn.role === 'user').length, 1);
      assert.equal(turns[0].text, '合成的用户原文');
      assert.equal(turns[0].message, row, 'a real user row keeps its existing edit handle');
      assert.equal(shown(turns).includes('Plan mode is ON'), false);
      assert.equal(api.isHumanMessage(row), true);
      assert.equal(api.isTurnStart(row), true);
      const baseOnly = { id: 10, role: 'user', content: `合成的用户原文\n\n${lightNote('/tmp/fixture-plans', [])}`, timestamp: 4 };
      assert.equal(api.buildTurns([baseOnly])[0].text, '合成的用户原文');
      const hinted = { id: 11, role: 'user', content: `合成的用户原文\n[Image attached at: /tmp/fixture.png]\n${NOTE}`, timestamp: 5 };
      assert.equal(api.buildTurns([hinted])[0].text, '合成的用户原文');
    });
    await test(`a pure plan-mode note is not shown as human speech (${modulePath})`, () => {
      const row = { id: 12, role: 'user', content: NOTE, timestamp: 6 };
      const turns = api.buildTurns([row]);
      assert.equal(turns.length, 0);
      assert.equal(shown(turns).includes('Plan mode is ON'), false);
      assert.equal(api.isHumanMessage(row), true, 'display hiding must not reclassify the stored row');
      assert.equal(api.isTurnStart(row), true);
    });
    await test(`user quotes, code, embeddings and near-matches of the plan note stay (${modulePath})`, () => {
      for (const content of [
        `合成原文\n\n> ${NOTE}`,
        `合成原文\n\n\`\`\`\n${NOTE}\n\`\`\``,
        `\`\`\`\n${NOTE}`,
        `请核对：${NOTE} 是否内部提示`,
        `开头\n\n${NOTE}\n\n结尾`,
        `原文提到「${NOTE}」`,
        `合成原文\n\nPlan mode is ON. Plans directory: /tmp/fixture-plans`,
        `${NOTE} 我自己写的`,
      ]) {
        const row = { id: 13, role: 'user', content, timestamp: 7 };
        const turns = api.buildTurns([row]);
        assert.equal(turns.length, 1);
        assert.equal(turns[0].role, 'user');
        assert.equal(turns[0].text, content);
      }
    });
    await test(`a shorter fence does not close a longer one, so the plan note stays inside the code block (${modulePath})`, () => {
      const open = '`'.repeat(5);
      const short = '`'.repeat(3);
      const inside = `${open}\ncode\n${short}\n${NOTE}`;
      const row = { id: 20, role: 'user', content: inside, timestamp: 20 };
      const stored = JSON.stringify(row);
      const turns = api.buildTurns([row]);
      assert.equal(JSON.stringify(row), stored, 'display projection must not rewrite the stored message');
      assert.equal(turns.length, 1);
      assert.equal(turns[0].role, 'user');
      assert.equal(turns[0].text, inside, 'kept=false: shorter fence must not close a longer opener');
      const equal = `${short}\ncode\n${short}\n\n${NOTE}`;
      assert.equal(api.buildTurns([{ id: 21, role: 'user', content: equal, timestamp: 21 }])[0].text, `${short}\ncode\n${short}`, 'equal-length close still removes only the appended note');
      const quoted = `合成原文\n\n> ${NOTE}`;
      assert.equal(api.buildTurns([{ id: 22, role: 'user', content: quoted, timestamp: 22 }])[0].text, quoted, 'blockquote stays');
      const closed = `${open}\ncode\n${short}\n${open}\n\n${NOTE}`;
      assert.equal(api.buildTurns([{ id: 23, role: 'user', content: closed, timestamp: 23 }])[0].text, `${open}\ncode\n${short}\n${open}`, 'a close at least as long as the opener still removes the note after it');
      const longerClose = `${short}\ncode\n${open}\n\n${NOTE}`;
      assert.equal(api.buildTurns([{ id: 24, role: 'user', content: longerClose, timestamp: 24 }])[0].text, `${short}\ncode\n${open}`, 'a longer fence still closes a shorter opener');
      const tildeInside = `${'~'.repeat(5)}\ncode\n${'~'.repeat(3)}\n${NOTE}`;
      assert.equal(api.buildTurns([{ id: 25, role: 'user', content: tildeInside, timestamp: 25 }])[0].text, tildeInside, 'tilde fences use the same length rule');
    });
    await test(`a complete light note that skips an absent earlier lever is removed (${modulePath})`, () => {
      for (const levers of [['bridge'], ['blocked'], ['skill'], ['bridge', 'blocked'], ['bridge', 'skill'], ['blocked', 'skill']]) {
        const note = lightNote('/tmp/fixture-plans', levers);
        const appended = { id: 30, role: 'user', content: `合成的用户原文\n\n${note}`, timestamp: 30 };
        assert.equal(api.buildTurns([appended])[0].text, '合成的用户原文', levers.join('+'));
        const pure = { id: 31, role: 'user', content: note, timestamp: 31 };
        const stored = JSON.stringify(pure);
        assert.equal(api.buildTurns([pure]).length, 0, levers.join('+'));
        assert.equal(JSON.stringify(pure), stored);
        assert.equal(api.isHumanMessage(pure), true, 'display hiding must not reclassify the stored row');
      }
      const wrongOrder = `${lightNote('/tmp/fixture-plans', [])} Do not load planning, TDD or debugging skills. Terminal and execute_code stay blocked until approval.`;
      assert.equal(api.buildTurns([{ id: 32, role: 'user', content: `合成原文\n\n${wrongOrder}`, timestamp: 32 }])[0].text, `合成原文\n\n${wrongOrder}`, 'lever sentences out of plugin order stay');
      const longPath = `/${'p'.repeat(199)}`;
      const dropped = lightNote(longPath, ['bridge', 'blocked', 'skill']);
      assert.equal(dropped, lightNote(longPath, []), 'levers that do not fit are dropped, matching light_note');
      assert.equal(api.buildTurns([{ id: 33, role: 'user', content: `合成的用户原文\n\n${dropped}`, timestamp: 33 }])[0].text, '合成的用户原文', 'a budget-shortened complete note is still removed');
      const exact = lightNote(`/${'p'.repeat(300)}`, []);
      assert.equal(exact.length, 400);
      assert.equal(api.buildTurns([{ id: 34, role: 'user', content: `合成的用户原文\n\n${exact}`, timestamp: 34 }])[0].text, '合成的用户原文', 'a complete note of exactly 400 characters is removed');
      const cut = lightNote(`/${'p'.repeat(500)}`, ['bridge', 'blocked', 'skill']);
      assert.equal(cut.length, 400);
      assert.equal(cut.endsWith('in prose.'), false, 'light_note cuts the base before the tail when the directory is too long');
      const kept = `合成原文\n\n${cut}`;
      const cutRow = { id: 35, role: 'user', content: kept, timestamp: 35 };
      const storedCut = JSON.stringify(cutRow);
      assert.equal(api.buildTurns([cutRow])[0].text, kept, 'a truncated light_note is not a complete paragraph and must stay');
      assert.equal(JSON.stringify(cutRow), storedCut);
      const pureCut = { id: 36, role: 'user', content: cut, timestamp: 36 };
      assert.equal(api.buildTurns([pureCut])[0].text, cut, 'a truncated prefix stays visible user text');
      assert.equal(api.isHumanMessage(pureCut), true);
    });
    await test(`image captions and upload cards survive plan-note stripping (${modulePath})`, () => {
      const parts = {
        id: 14,
        role: 'user',
        content: [
          { type: 'text', text: '合成图片说明' },
          { type: 'image_url', image_url: { url: 'data:image/png;base64,aaaa' } },
          { type: 'text', text: NOTE },
        ],
        timestamp: 8,
      };
      const partTurns = api.buildTurns([parts]);
      assert.equal(partTurns[0].text, '合成图片说明');
      assert.deepEqual(partTurns[0].images, ['data:image/png;base64,aaaa']);
      assert.equal(partTurns[0].message, parts);
      const upload = {
        id: 15,
        role: 'user',
        content: `合成图片说明\n\n[附件已上传：/root/hermes-uploads/fixture.png（12 KB）]\n（这是图片文件，请用看图工具读取该路径）\n\n${NOTE}`,
        timestamp: 9,
      };
      const uploadTurns = api.buildTurns([upload]);
      assert.equal(uploadTurns[0].text, '合成图片说明');
      assert.equal(uploadTurns[0].uploads[0].name, 'fixture.png');
      assert.equal(uploadTurns[0].uploads[0].image, true);
      assert.equal(shown(uploadTurns).includes('Plan mode is ON'), false);
    });
    await test(`queue, steer and continuation guards are not loosened by plan-note display (${modulePath})`, () => {
      const queued = { id: 16, role: 'user', display_kind: 'internal_notification', input_origin: 'api_queue', timestamp: 10, content: `我的原话\n\n${NOTE}` };
      const queuedTurns = api.buildTurns([queued]);
      assert.equal(queuedTurns[0].role, 'user');
      assert.equal(queuedTurns[0].text, '我的原话');
      assert.equal(queuedTurns[0].message, undefined);
      assert.equal(api.isTurnStart(queued), true);
      const steer = { id: 17, role: 'user', display_kind: 'steer', timestamp: 11, content: `[OUT-OF-BAND USER MESSAGE]\n合成插话\n\n${NOTE}\n[/OUT-OF-BAND USER MESSAGE]` };
      const steerTurns = api.buildTurns([steer]);
      assert.equal(steerTurns[0].steer, true);
      assert.equal(steerTurns[0].text, '合成插话');
      assert.equal(steerTurns[0].message, undefined);
      assert.equal(api.isTurnStart(steer), false);
      const now = 1_800_000_000;
      const done = { id: 5, role: 'user', display_kind: 'async_delegation_complete', timestamp: now - 10, content: '[ASYNC DELEGATION BATCH COMPLETE — deleg_fixture]\nfinished' };
      const prior = [{ id: 1, role: 'user', content: '查一下', timestamp: now - 100 }, { id: 4, role: 'assistant', content: '等结果', timestamp: now - 80 }];
      assert.equal(api.continuationState([...prior, done, { id: 6, role: 'user', content: NOTE, timestamp: now - 5 }]).trigger, null);
      assert.equal(api.continuationState([...prior, done, { id: 7, role: 'user', content: `先别管它\n\n${NOTE}`, timestamp: now - 4 }]).trigger, null);
    });
  }
} finally {
  await server.close();
}
